Check(J(hub.Command(a,create)).GetProperty("room").GetProperty("roomId").GetString()==rid,"create idempotent");
F("STATION_ONLINE_REQUEST_REUSED",()=>hub.Command(a,create with{ItemId="another"}));
Check(!J(hub.Command(c,C("heartbeat"))).GetRawText().Contains("connectionPassword"),"outsider receives no connection secret");
hub.Command(a,C("invite") with{RoomId=rid,PeerId=bv.GetProperty("selfId").GetString()});
Check(J(hub.Command(b,C("heartbeat"))).GetProperty("invites").GetArrayLength()==1,"invitation delivered");
F("STATION_ONLINE_ROOM_NOT_FOUND",()=>hub.Command(c,C("chat") with{RoomId=rid,Text="outsider"}));
