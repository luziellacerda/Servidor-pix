using System.Text.Json;
using TurboRamaSuiteOnlineServer.Online;
long now=1000;int checks=0;
string hash=new('a',64),otherHash=new('b',64);
var engine=new OnlineEngine("test-engine","snes",hash,hash);
var hub=new StationOnline([engine],id=>id=="test-item"?"snes":null,()=>now);
var a=new OnlineIdentity("synthetic-license-A","synthetic-device-A");
var b=new OnlineIdentity("synthetic-license-B","synthetic-device-B");
var c=new OnlineIdentity("synthetic-license-C","synthetic-device-C");
OnlineCommand C(string action)=>new(action,Guid.NewGuid().ToString());
JsonElement J(object value)=>JsonSerializer.SerializeToElement(value,new JsonSerializerOptions(JsonSerializerDefaults.Web));
void Check(bool ok,string name){checks++;if(!ok)throw new Exception(name);}
void F(string code,Action action){try{action();throw new Exception("accepted "+code);}catch(OnlineFailure x){Check(x.Code==code,code);}}
F("STATION_ONLINE_ENTER_REQUIRED",()=>hub.Command(a,C("heartbeat")));
F("STATION_ONLINE_TEXT_INVALID",()=>hub.Command(a,C("enter") with{Nickname="bad\nname"}));
var av=J(hub.Command(a,C("enter") with{Nickname="Jogador A"}));
var bv=J(hub.Command(b,C("enter") with{Nickname="Jogador B"}));
var cv=J(hub.Command(c,C("enter") with{Nickname="Jogador C"}));
Check(cv.GetProperty("totalPeers").GetInt32()==3,"three authenticated peers");
Check(!cv.GetRawText().Contains("synthetic-license"),"license IDs never public");
var create=C("create") with{ItemId="test-item",EngineId="test-engine",ContentSha256=hash,OptionsSha256=hash,CoreSha256=hash,RuntimeSha256=hash};
