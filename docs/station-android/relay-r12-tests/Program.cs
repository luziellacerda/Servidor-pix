F("STATION_ONLINE_BUILD_MISMATCH",()=>hub.Command(b,join with{ContentSha256=otherHash,RequestId=Guid.NewGuid().ToString()}));
hub.Command(b,join);
F("STATION_ONLINE_ROOM_FULL",()=>hub.Command(c,join with{RequestId=Guid.NewGuid().ToString()}));
