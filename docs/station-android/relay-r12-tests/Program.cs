var poll=hub.Events(a,before.GetProperty("instance").GetString(),before.GetProperty("revision").GetInt64(),0,CancellationToken.None);
Check(!poll.IsCompleted,"events wait without repeated polling");
var message=C("chat") with{RoomId=rid,Text="Vamos jogar!"};hub.Command(b,message);
var updated=J(await poll.WaitAsync(TimeSpan.FromSeconds(1)));
Check(updated.GetProperty("room").GetProperty("messages").GetArrayLength()==1,"chat wakes events immediately");
hub.Command(b,message);
Check(J(hub.Command(a,C("heartbeat"))).GetProperty("room").GetProperty("messages").GetArrayLength()==1,"chat retry has no duplicate");
F("STATION_ONLINE_CHAT_LIMIT",()=>hub.Command(b,C("chat") with{RoomId=rid,Text="flood"}));
hub.Command(a,C("ready") with{RoomId=rid,Value=true});hub.Command(b,C("ready") with{RoomId=rid,Value=true});
F("STATION_ONLINE_HOST_REQUIRED",()=>hub.Command(b,C("start") with{RoomId=rid,Address="192.168.1.10",Port=55435}));
F("STATION_ONLINE_ENDPOINT_INVALID",()=>hub.Command(a,C("start") with{RoomId=rid,Address="127.0.0.1",Port=55435}));
F("STATION_ONLINE_ENDPOINT_INVALID",()=>hub.Command(a,C("start") with{RoomId=rid,Address="224.0.0.1",Port=55435}));
var started=J(hub.Command(a,C("start") with{RoomId=rid,Address="192.168.1.10",Port=55435}));
Check(started.GetProperty("room").GetProperty("state").GetString()=="starting","guest waits for actual native host listening");
F("STATION_ONLINE_HOST_REQUIRED",()=>hub.Command(b,C("host-listening") with{RoomId=rid}));
var listening=J(hub.Command(a,C("host-listening") with{RoomId=rid}));
Check(listening.GetProperty("room").GetProperty("state").GetString()=="connecting","host listening signal releases guest but does not claim game synchronized");
hub.Command(b,C("leave"));
Check(J(hub.Command(a,C("heartbeat"))).GetProperty("room").ValueKind==JsonValueKind.Null,"leaving match closes session for host");
Check(J(hub.Command(a,create)).GetProperty("room").ValueKind==JsonValueKind.Null,"old retry cannot resurrect a departed room or expose its secret");
now+=11000;
